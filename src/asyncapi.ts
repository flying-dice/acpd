import { stringify } from "yaml";
import { version } from "../package.json";
import type { Peer } from "./acp.ts";
import { messageName } from "./openapi.ts";

/**
 * acpd's AsyncAPI 3.1 document. It describes the `/acp` WebSocket channel and
 * the messages each peer sends. It complements `openapi.yaml`, which describes
 * the HTTP handshake and holds the message schemas this document references.
 */

/** JSON Schema 2020-12 is the dialect of the ACP schemas and of OpenAPI 3.2. */
const SCHEMA_FORMAT = "application/schema+json;version=draft-2020-12";
const openApiSchema = (id: string) => ({ $ref: `./openapi.yaml#/components/schemas/${id}` });
const ref = (path: string) => ({ $ref: `#/${path}` });

function message(sender: Peer) {
    return {
        name: messageName(sender),
        title: `ACP ${sender} message`,
        summary: `A JSON-RPC message ${sender === "client" ? "a client sends to the agent" : "the agent sends to a client"} under ACP v1.`,
        contentType: "application/json",
        correlationId: ref("components/correlationIds/jsonRpcId"),
        payload: { schemaFormat: SCHEMA_FORMAT, schema: openApiSchema(messageName(sender)) },
    };
}

export function buildAsyncApi() {
    const messages = Object.fromEntries((["client", "agent"] as const).map((sender) => [messageName(sender), message(sender)]));
    const channelMessages = (sender: Peer) => [ref(`channels/acp/messages/${messageName(sender)}`)];

    return {
        asyncapi: "3.1.0",
        info: {
            title: "acpd",
            version,
            description: [
                "Minimal Agent Client Protocol (ACP) proxy. This document describes acpd's side of the `/acp` WebSocket channel:",
                "the messages it receives from clients and sends to them. `openapi.yaml` describes the HTTP handshake and error",
                "responses, and holds the ACP v1 schemas the messages reference.",
                "",
                "Each WebSocket text frame carries one JSON-RPC 2.0 message. acpd speaks ACP v1: send `initialize`",
                "first, and the agent must answer with `protocolVersion` 1.",
                "Responses are matched to requests by `id`, and either side may send requests.",
            ].join("\n"),
            externalDocs: { description: "Agent Client Protocol", url: "https://agentclientprotocol.com" },
        },
        defaultContentType: "application/json",
        servers: {
            local: {
                host: "127.0.0.1:3000",
                protocol: "ws",
                description: "Default local address. `host` and `port` in the config file change it.",
            },
        },
        channels: {
            acp: {
                address: "/acp",
                title: "ACP connection",
                description: "One ACP connection to the selected agent. Closing the socket stops the agent process.",
                messages,
                bindings: {
                    ws: {
                        method: "GET",
                        query: {
                            type: "object",
                            properties: {
                                agentId: {
                                    type: "string",
                                    pattern: "^[\\w.-]+$",
                                    description: "ID of a configured agent. Defaults to the config's `defaultAgent`. This is not part of ACP.",
                                },
                            },
                        },
                        bindingVersion: "0.1.0",
                    },
                },
            },
        },
        operations: {
            receiveClientMessage: {
                action: "receive",
                channel: ref("channels/acp"),
                title: "Receive a client message",
                summary: "acpd validates the message and relays it to the agent.",
                messages: channelMessages("client"),
            },
            sendAgentMessage: {
                action: "send",
                channel: ref("channels/acp"),
                title: "Send an agent message",
                summary: "acpd relays a validated message from the agent to the client.",
                messages: channelMessages("agent"),
            },
        },
        components: {
            correlationIds: {
                jsonRpcId: { description: "JSON-RPC request ID, which its response repeats.", location: "$message.payload#/id" },
            },
        },
    };
}

export function asyncApiYaml(): string {
    return `# Generated by \`bun run asyncapi\` from src/asyncapi.ts. Do not edit.\n${stringify(buildAsyncApi(), { lineWidth: 0 })}`;
}

if (import.meta.main) {
    await Bun.write(new URL("../asyncapi.yaml", import.meta.url), asyncApiYaml());
    console.log("Wrote asyncapi.yaml");
}
